// Checkout handler (100% inline alert)
window.handleCheckout = function() {
  const userStr = localStorage.getItem('twareed_user');
  const currentLang = localStorage.getItem('twareed_lang') || 'ar';

  if (!userStr) {
    window.location.href = 'login-signup.html';
    return;
  }

  const user = JSON.parse(userStr);
  const cart = getCart();
  if (cart.length === 0) return;

  const totalAmount = cart.reduce((sum, item) => sum + (parseFloat(item.price_omr) || 0) * (item.quantity || 1), 0).toFixed(2);
  
  // Clear cart on successful order
  saveCart([]);
  renderCartPage();

  const successMsg = currentLang === 'ar'
    ? `تم إرسال طلبك بنجاح بإجمالي ${totalAmount} ر.ع. (الدفع عند الاستلام) باسم ${user.full_name}! سيتم إرسال رسوم التوصيل على رقم الجوال ${user.phone} والبريد الإلكتروني ${user.email} بعد احتسابها والتحقق من توفر القطع.`
    : `Your order of ${totalAmount} OMR (Cash on Delivery) for ${user.full_name} has been placed! Delivery fees will be sent to your mobile (${user.phone}) and email (${user.email}) after calculation and verification of parts availability.`;

  showAlert('cart-alert', successMsg, 'success');
};

// Fetch products from backend CSV API
async function loadProducts() {
  try {
    const res = await fetch('/api/products');
    if (!res.ok) throw new Error('Failed to fetch');
    const data = await res.json();
    globalProducts = data;
    
    // Check if on catalog page
    if (document.getElementById('products-container')) {
      renderProducts(globalProducts);
    }

    // Check if on single product details page
    if (document.getElementById('product-details-container')) {
      renderProductDetails(globalProducts);
    }
  } catch (err) {
    console.error('Error loading products:', err);
  }
}

