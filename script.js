// Filter products based on search input
function setupSearch() {
  const searchInput = document.getElementById('product-search');
  if (!searchInput) return;

  searchInput.addEventListener('input', (e) => {
    const q = e.target.value.toLowerCase().trim();
    const currentLang = localStorage.getItem('twareed_lang') || 'ar';

    if (!q) {
      renderProducts(globalProducts);
      return;
    }

    const filtered = globalProducts.filter((p) => {
      const name = getProductName(p, currentLang).toLowerCase();
      const serial = (p.serial_number || '').toLowerCase();
      const origin = (p.origin || '').toLowerCase();
      return name.includes(q) || serial.includes(q) || origin.includes(q);
    });

    renderProducts(filtered);
  });
}

// Switch between Login and Signup tabs
function switchAuthTab(targetTab) {
  const tabLoginBtn = document.getElementById('tab-login');
  const tabSignupBtn = document.getElementById('tab-signup');
  const formLogin = document.getElementById('form-login');
  const formSignup = document.getElementById('form-signup');

  if (!tabLoginBtn || !tabSignupBtn || !formLogin || !formSignup) return;

  if (targetTab === 'signup') {
    tabSignupBtn.classList.add('active');
    tabLoginBtn.classList.remove('active');
    formSignup.classList.add('active');
    formLogin.classList.remove('active');
  } else {
    tabLoginBtn.classList.add('active');
    tabSignupBtn.classList.remove('active');
    formLogin.classList.add('active');
    formSignup.classList.remove('active');
  }
}

// Inline Alert Helper Function
function showAlert(alertElId, message, type = 'error') {
  const alertEl = document.getElementById(alertElId);
  if (!alertEl) return;

  alertEl.className = `auth-alert alert-${type}`;
  const icon = type === 'success' ? '✅' : type === 'warning' ? '⚠️' : '❌';
  alertEl.innerHTML = `<span>${icon}</span> <span>${message}</span>`;
  alertEl.style.display = 'flex';
  alertEl.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
}

function hideAlert(alertElId) {
  const alertEl = document.getElementById(alertElId);
  if (alertEl) {
    alertEl.style.display = 'none';
    alertEl.innerHTML = '';
  }
}

