// Initial setup on page load
document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('twareed_lang') || 'ar';
  if (languageSelect) {
    languageSelect.value = savedLang;
    updateLanguage(savedLang);

    languageSelect.addEventListener('change', (e) => {
      updateLanguage(e.target.value);
      setupUserSessionUI();
    });
  }

  setupUserSessionUI();
  updateCartBadge();
  renderCartPage();
  checkFlashMessage();
  loadProducts();
  setupSearch();

  // Tab click listeners
  const tabLoginBtn = document.getElementById('tab-login');
  const tabSignupBtn = document.getElementById('tab-signup');

  if (tabLoginBtn && tabSignupBtn) {
    tabLoginBtn.addEventListener('click', () => switchAuthTab('login'));
    tabSignupBtn.addEventListener('click', () => switchAuthTab('signup'));
  }

  // Footer switch links
  document.querySelectorAll('.link-switch').forEach((btn) => {
    btn.addEventListener('click', () => {
      const target = btn.getAttribute('data-target');
      switchAuthTab(target);
    });
  });

  // Toggle password visibility
  document.querySelectorAll('.btn-toggle-pw').forEach((btn) => {
    btn.addEventListener('click', () => {
      const input = btn.previousElementSibling;
      if (input && input.type === 'password') {
        input.type = 'text';
      } else if (input) {
        input.type = 'password';
      }
    });
  });

  // Form submission handling
  const formSignup = document.getElementById('form-signup');
  if (formSignup) {
    formSignup.addEventListener('submit', async (e) => {
      e.preventDefault();
      hideAlert('signup-alert');

      const submitBtn = formSignup.querySelector('.btn-auth-submit');
      const originalText = submitBtn.textContent;

      const full_name = document.getElementById('signup-name').value;
      const phone = document.getElementById('signup-phone').value;
      const email = document.getElementById('signup-email').value;
      const country = document.getElementById('signup-country').value;
      const city = document.getElementById('signup-city').value;
      const password = document.getElementById('signup-password').value;
      const confirmPassword = document.getElementById('signup-confirm-password').value;

      if (password !== confirmPassword) {
        const lang = localStorage.getItem('twareed_lang') || 'ar';
        const msg = lang === 'ar' ? 'كلمات المرور غير متطابقة!' : 'Passwords do not match!';
        showAlert('signup-alert', msg, 'error');
        return;
      }

      try {
        submitBtn.disabled = true;
        submitBtn.textContent = '...';

        const res = await fetch('/api/auth/signup', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ full_name, phone, email, country, city, password })
        });

        const data = await res.json();

        if (res.ok && data.success) {
          localStorage.setItem('twareed_user', JSON.stringify(data.user));

          const lang = localStorage.getItem('twareed_lang') || 'ar';
          const t = translations[lang] || translations.ar;
          const welcomeMsg = `مرحباً بك، ${data.user.full_name}! ${t.accountCreatedSuccess || 'تم إنشاء حسابك وتسجيل دخولك بنجاح في سلطنة عمان!'}`;
          localStorage.setItem('twareed_flash_msg', welcomeMsg);

          window.location.href = 'index.html';
        } else {
          showAlert('signup-alert', data.message || 'حدث خطأ أثناء التسجيل', 'error');
        }
      } catch (err) {
        showAlert('signup-alert', 'تعذر الاتصال بالخادم وقاعدة البيانات: ' + err.message, 'error');
      } finally {
        submitBtn.disabled = false;
        submitBtn.textContent = originalText;
      }
    });
  }

  const formLogin = document.getElementById('form-login');
  if (formLogin) {
    formLogin.addEventListener('submit', async (e) => {
      e.preventDefault();
      hideAlert('login-alert');

      const submitBtn = formLogin.querySelector('.btn-auth-submit');
      const originalText = submitBtn.textContent;

      const identifier = document.getElementById('login-email').value;
      const password = document.getElementById('login-password').value;

      try {
        submitBtn.disabled = true;
        submitBtn.textContent = '...';

        const res = await fetch('/api/auth/login', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ identifier, password })
        });

        const data = await res.json();

        if (res.ok && data.success) {
          localStorage.setItem('twareed_user', JSON.stringify(data.user));

          const welcomeMsg = `مرحباً بعودتك، ${data.user.full_name}!`;
          localStorage.setItem('twareed_flash_msg', welcomeMsg);

          window.location.href = 'index.html';
        } else {
          showAlert('login-alert', data.message || 'بيانات الدخول غير صحيحة', 'error');
        }
      } catch (err) {
        showAlert('login-alert', 'تعذر الاتصال بالخادم: ' + err.message, 'error');
      } finally {
        submitBtn.disabled = false;
        submitBtn.textContent = originalText;
      }
    });
  }
});
