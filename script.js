// Cart State Management (localStorage)
function getCart() {
  try {
    return JSON.parse(localStorage.getItem('twareed_cart')) || [];
  } catch (e) {
    return [];
  }
}

function saveCart(cart) {
  localStorage.setItem('twareed_cart', JSON.stringify(cart));
  updateCartBadge();
}

function updateCartBadge() {
  const badge = document.getElementById('cart-badge-count');
  if (!badge) return;
  const cart = getCart();
  const totalCount = cart.reduce((sum, item) => sum + (item.quantity || 1), 0);
  badge.textContent = totalCount;
  badge.style.display = totalCount > 0 ? 'inline-block' : 'none';
}

// Custom In-Page Verification Modal (Promise-based, 0 browser popups)
function showVerificationDialog({ title, description, confirmText = 'تأكيد', cancelText = 'إلغاء', isDanger = false }) {
  return new Promise((resolve) => {
    // Remove any existing modal
    const existing = document.getElementById('custom-verify-modal');
    if (existing) existing.remove();

    const currentLang = localStorage.getItem('twareed_lang') || 'ar';
    const finalConfirm = confirmText || (currentLang === 'ar' ? 'تأكيد' : 'Confirm');
    const finalCancel = cancelText || (currentLang === 'ar' ? 'إلغاء' : 'Cancel');

    const modal = document.createElement('div');
    modal.id = 'custom-verify-modal';
    modal.className = 'verify-modal-backdrop';
    modal.innerHTML = `
      <div class="verify-modal-box">
        <div class="verify-modal-icon ${isDanger ? 'danger' : ''}">
          <svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
            ${isDanger 
              ? '<polyline points="3 6 5 6 21 6"></polyline><path d="M19 6v14a2 2 0 0 1-2 2H7a2 2 0 0 1-2-2V6m3 0V4a2 2 0 0 1 2-2h4a2 2 0 0 1 2 2v2"></path>' 
              : '<circle cx="12" cy="12" r="10"></circle><line x1="12" y1="8" x2="12" y2="12"></line><line x1="12" y1="16" x2="12.01" y2="16"></line>'}
          </svg>
        </div>
        <h3 class="verify-modal-title">${title}</h3>
        <p class="verify-modal-desc">${description}</p>
        <div class="verify-modal-actions">
          <button type="button" class="btn-modal-cancel" id="verify-modal-cancel-btn">${finalCancel}</button>
          <button type="button" class="btn-modal-confirm ${isDanger ? 'danger' : ''}" id="verify-modal-confirm-btn">${finalConfirm}</button>
        </div>
      </div>
    `;

    document.body.appendChild(modal);

    const confirmBtn = document.getElementById('verify-modal-confirm-btn');
    const cancelBtn = document.getElementById('verify-modal-cancel-btn');

    confirmBtn.onclick = () => {
      modal.remove();
      resolve(true);
    };

    cancelBtn.onclick = () => {
      modal.remove();
      resolve(false);
    };

    modal.onclick = (e) => {
      if (e.target === modal) {
        modal.remove();
        resolve(false);
      }
    };
  });
}

// Order / Add Part action handler (with verification message)
window.handleOrder = async function(productId) {
  const currentLang = localStorage.getItem('twareed_lang') || 'ar';
  const item = globalProducts.find(p => p.id === productId);
  if (!item) return;

  const name = getProductName(item, currentLang);
  const promptTitle = currentLang === 'ar' ? 'تأكيد إضافة القطعة' : 'Confirm Add to Cart';
  const promptDesc = currentLang === 'ar' 
    ? `هل ترغب في إضافة "${name}" بسعر ${item.price_omr} ر.ع. إلى سلة الطلبات؟` 
    : `Would you like to add "${name}" (${item.price_omr} OMR) to your shopping cart?`;

  const verified = await showVerificationDialog({
    title: promptTitle,
    description: promptDesc,
    confirmText: currentLang === 'ar' ? 'نعم، أضف للسلة' : 'Yes, Add to Cart'
  });

  if (!verified) return;

  const cart = getCart();
  const existing = cart.find(c => c.id === productId);

  if (existing) {
    existing.quantity = (existing.quantity || 1) + 1;
  } else {
    cart.push({
      id: item.id,
      image: item.image,
      name_ar: item.name_ar,
      name_en: item.name_en,
      name_ur: item.name_ur,
      name_hi: item.name_hi,
      name_ml: item.name_ml,
      serial_number: item.serial_number,
      origin: item.origin,
      origin_ar: item.origin_ar,
      origin_en: item.origin_en,
      origin_ur: item.origin_ur,
      origin_hi: item.origin_hi,
      origin_ml: item.origin_ml,
      price_omr: item.price_omr,
      quantity: 1
    });
  }

  saveCart(cart);

  const successMsg = currentLang === 'ar'
    ? `تمت إضافة القطعة "${name}" إلى سلة الطلبات بنجاح!`
    : `Item "${name}" added to your cart successfully!`;

  if (document.getElementById('product-alert')) {
    showAlert('product-alert', successMsg, 'success');
  } else if (document.getElementById('home-welcome-alert')) {
    showAlert('home-welcome-alert', successMsg, 'success');
  }
};

// Modify Cart Quantities (with verification messages)
window.changeCartQty = async function(productId, delta) {
  const cart = getCart();
  const item = cart.find(c => c.id === productId);
  if (!item) return;

  const currentLang = localStorage.getItem('twareed_lang') || 'ar';
  const name = getProductName(item, currentLang);

  if (delta > 0) {
    // Verification when increasing
    const verified = await showVerificationDialog({
      title: currentLang === 'ar' ? 'زيادة كمية القطعة' : 'Increase Quantity',
      description: currentLang === 'ar' 
        ? `هل تريد زيادة عدد "${name}" في السلة إلى ${(item.quantity || 1) + 1}؟` 
        : `Increase quantity of "${name}" to ${(item.quantity || 1) + 1}?`,
      confirmText: currentLang === 'ar' ? 'زيادة' : 'Increase'
    });
    if (!verified) return;
  } else {
    // Verification when decreasing
    if (item.quantity <= 1) {
      removeFromCart(productId);
      return;
    }

    const verified = await showVerificationDialog({
      title: currentLang === 'ar' ? 'تقليل كمية القطعة' : 'Decrease Quantity',
      description: currentLang === 'ar' 
        ? `هل تريد تقليل عدد "${name}" في السلة إلى ${(item.quantity || 1) - 1}؟` 
        : `Decrease quantity of "${name}" to ${(item.quantity || 1) - 1}?`,
      confirmText: currentLang === 'ar' ? 'تقليل' : 'Decrease'
    });
    if (!verified) return;
  }

  item.quantity = (item.quantity || 1) + delta;
  saveCart(cart);
  renderCartPage();
};

window.removeFromCart = async function(productId) {
  const cart = getCart();
  const item = cart.find(c => c.id === productId);
  if (!item) return;

  const currentLang = localStorage.getItem('twareed_lang') || 'ar';
  const name = getProductName(item, currentLang);

  const verified = await showVerificationDialog({
    title: currentLang === 'ar' ? 'حذف القطعة من السلة' : 'Remove Item',
    description: currentLang === 'ar' 
      ? `هل أنت متأكد من حذف "${name}" بالكامل من سلة الطلبات؟` 
      : `Are you sure you want to remove "${name}" from your cart?`,
    confirmText: currentLang === 'ar' ? 'نعم، حذف القطعة' : 'Yes, Remove',
    isDanger: true
  });

  if (!verified) return;

  const updatedCart = cart.filter(c => c.id !== productId);
  saveCart(updatedCart);
  renderCartPage();

  const msg = currentLang === 'ar' ? `تم حذف "${name}" من السلة.` : `"${name}" removed from cart.`;
  showAlert('cart-alert', msg, 'warning');
};

