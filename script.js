function updateLanguage(lang) {
  const data = translations[lang] || translations.ar;
  
  // Set html document attributes
  document.documentElement.lang = lang;
  document.documentElement.dir = data.dir;

  // Update text elements
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (data[key]) {
      el.textContent = data[key];
    }
  });

  // Update placeholder attributes
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (data[key]) {
      el.placeholder = data[key];
    }
  });

  // Update value attributes for readonly inputs like country
  document.querySelectorAll('[data-i18n-value]').forEach((el) => {
    const key = el.getAttribute('data-i18n-value');
    if (data[key]) {
      el.value = data[key];
    }
  });

  // Persist language choice
  localStorage.setItem('twareed_lang', lang);

  // Re-render products with active language
  if (globalProducts.length > 0) {
    if (document.getElementById('products-container')) {
      renderProducts(globalProducts);
    }
    if (document.getElementById('product-details-container')) {
      renderProductDetails(globalProducts);
    }
  }
  if (document.getElementById('cart-content-wrapper')) {
    renderCartPage();
  }
}

// Get localized product name
function getProductName(product, lang) {
  switch (lang) {
    case 'en': return product.name_en || product.name_ar;
    case 'ur': return product.name_ur || product.name_ar;
    case 'hi': return product.name_hi || product.name_ar;
    case 'ml': return product.name_ml || product.name_ar;
    default: return product.name_ar;
  }
}

// Get localized product origin
function getProductOrigin(product, lang) {
  switch (lang) {
    case 'en': return product.origin_en || product.origin || product.origin_ar;
    case 'ur': return product.origin_ur || product.origin || product.origin_ar;
    case 'hi': return product.origin_hi || product.origin || product.origin_ar;
    case 'ml': return product.origin_ml || product.origin || product.origin_ar;
    default: return product.origin_ar || product.origin;
  }
}

